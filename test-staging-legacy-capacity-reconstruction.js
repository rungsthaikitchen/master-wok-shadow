'use strict';
const assert=require('node:assert/strict');
const {allocate,loadFor,reconstructLegacySlots}=require('./staging-legacy-capacity-reconstruction');
const map=new Map();
assert.equal(allocate(map,1020,2),true);
assert.equal(map.get(1010),1);
assert.equal(map.get(1015),1);
assert.equal(allocate(new Map(map),1020,1),false);
assert.equal(allocate(new Map(map),1025,1),true);
assert.equal(allocate(new Map(),990,1),false);
assert.equal(loadFor({items:[{qty:2,kitchen_load:1},{qty:1,kitchen_load:0}]}),2);
assert.equal(loadFor({items:[{qty:1}]}),null);
const snapshot={orders:[{id:'A',status:'confirmed',local_ready_minute:1050,items:[{qty:2,kitchen_load:1}]}]};
const result=reconstructLegacySlots(snapshot,{candidateLoad:1,priorCount:1,startMinute:1040,endMinute:1055});
assert.equal(result.status,'RECONSTRUCTED_CAPACITY_ONLY');
assert.deepEqual(result.slots.map(s=>s.legacyCapacityFit),[true,false,false,true]);
assert.equal(result.bookingApprovalAllowed,false);
const missing=reconstructLegacySlots({orders:[{...snapshot.orders[0],items:[{qty:2}]}]},{candidateLoad:1,priorCount:1});
assert.equal(missing.status,'UNVERIFIED');
assert.equal(missing.slots.length,0);
console.log('PASS: offline legacy capacity reconstruction respects 5-minute continuous steps and missing loads');
